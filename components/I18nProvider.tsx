interface I18nValue {
  language: AppLanguage
  setLanguage: (language: AppLanguage) => void
  locale: string
  t: (key: TranslationKey, values?: Record<string, string | number>) => string
  pageLabel: (count: number) => string
  statusLabel: (status: string) => string
}

const I18nContext = createContext<I18nValue | null>(null)

function getStoredLanguage(): AppLanguage {
  if (typeof window === 'undefined') return 'tr'
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY)
    return LANGUAGE_OPTIONS.some(item => item.code === stored) ? stored as AppLanguage : 'tr'
  } catch {
    return 'tr'
  }
}

function interpolate(template: string, values?: Record<string, string | number>) {
  if (!values) return template
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? `{${key}}`))
}

if (typeof window !== 'undefined') {
  const base = process.env.NEXT_PUBLIC_API_BASE_URL
  if (base) {
    const originalFetch = window.fetch
    window.fetch = function (input, init) {
      if (typeof input === 'string' && input.startsWith('/api/')) {
        return originalFetch(base + input, init)
      } else if (input instanceof URL) {
        if (input.pathname.startsWith('/api/')) {
          return originalFetch(new URL(base + input.pathname + input.search), init)
        }
      } else if (input instanceof Request) {
        try {
          const urlObj = new URL(input.url)
          if (urlObj.pathname.startsWith('/api/')) {
            const newRequest = new Request(base + urlObj.pathname + urlObj.search, input)
            return originalFetch(newRequest, init)
          }
        } catch (e) {
          // ignore
        }
      }
      return originalFetch(input, init)
    }
  }
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<AppLanguage>('tr')

  useEffect(() => {
    const timer = window.setTimeout(() => setLanguageState(getStoredLanguage()), 0)
    return () => window.clearTimeout(timer)
  }, [])

  const setLanguage = useCallback((next: AppLanguage) => {
    setLanguageState(next)
    try {
      window.localStorage.setItem(STORAGE_KEY, next)
    } catch (e) {
      console.warn(e)
    }
    document.documentElement.lang = next
  }, [])

  useEffect(() => {
    document.documentElement.lang = language
  }, [language])

  const value = useMemo<I18nValue>(() => {
    const dictionary = translations[language]
    const locale = language === 'tr' ? 'tr-TR' : language === 'de' ? 'de-DE' : 'en-US'

    const t: I18nValue['t'] = (key, values) => {
      const template = dictionary[key] || translations.en[key] || key
      return interpolate(template, values)
    }

    return {
      language,
      setLanguage,
      locale,
      t,
      pageLabel: count => {
        if (language === 'tr') return `${count} ${t('common.page')}`
        const key = count === 1 ? 'common.page' : 'common.pages'
        return `${count} ${t(key)}`
      },
      statusLabel: status => t(`status.${status}` as TranslationKey),
    }
  }, [language, setLanguage])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const context = useContext(I18nContext)
  if (!context) throw new Error('useI18n must be used inside I18nProvider')
  return context
}
