import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(readFileSync(path.join(root, 'node_modules/pdfjs-dist/package.json'), 'utf8'))
const src = path.join(root, 'node_modules/pdfjs-dist/build/pdf.worker.min.mjs')
const publicDir = path.join(root, 'public')
const dest = path.join(publicDir, 'pdf.worker.min.mjs')

mkdirSync(publicDir, { recursive: true })
copyFileSync(src, dest)

writeFileSync(
  path.join(publicDir, 'pdf.worker.version.json'),
  `${JSON.stringify({ version: pkg.version, syncedAt: new Date().toISOString() }, null, 2)}\n`,
)

writeFileSync(
  path.join(root, 'lib/pdfWorker.generated.ts'),
  `// Generated by scripts/sync-pdf-worker.mjs — do not edit.\nexport const PDFJS_VERSION = '${pkg.version}'\nexport const PDF_WORKER_SRC = '/pdf.worker.min.mjs?v=${pkg.version}'\n`,
)

console.log(`Synced pdf.worker.min.mjs (${pkg.version})`)
