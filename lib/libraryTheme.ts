export function getLibraryThemeStyle(theme: LibraryTheme) {
  const { vars, progressColor, progressGlow } = LIBRARY_THEME[theme]
  return {
    '--lib-bg': vars.bg,
    '--lib-header': vars.header,
    '--lib-surface': vars.surface,
    '--lib-surface-strong': vars.surfaceStrong,
    '--lib-surface-muted': vars.surfaceMuted,
    '--lib-surface-subtle': vars.surfaceSubtle,
    '--lib-border': vars.border,
    '--lib-border-strong': vars.borderStrong,
    '--lib-text': vars.text,
    '--lib-text-secondary': vars.textSecondary,
    '--lib-text-muted': vars.textMuted,
    '--lib-accent': progressColor,
    '--lib-accent-surface': vars.accentSurface,
    '--lib-accent-border': vars.accentBorder,
    '--lib-accent-soft': vars.accentSoft,
    '--lib-accent-strong': vars.accentStrong,
    '--lib-mesh-secondary': vars.meshSecondary,
    '--lib-shadow': vars.shadow,
    '--progress-color': progressColor,
    '--progress-glow': progressGlow,
  }
}

export function getLibraryTheme(): LibraryTheme {
  if (typeof window === 'undefined') return 'dark'
  return (localStorage.getItem(THEME_STORAGE.library) as LibraryTheme) || 'dark'
}
